#!/usr/bin/env python3
"""Phase-0 file-size ratchet measurement for plan-coder issue #23.

Phase 0 is measurement only: no checker, no gate, no supervisor wiring.
This script produces the two raw tables the issue asks for:

  inventory       The §1 inventory baseline: per repo, split by src / test /
                  fixture, file counts, token totals and over-limit counts.
                  Regenerated from the clones (read-only scans) so that
                  harness-tune can re-run it later.

  retrospective   The would-block analysis of the most recent N
                  ``pr_opened`` rows in the worker ledger: every file
                  changed by a worker PR is classified (new-over /
                  crossing / over-growing / over-shrinking / under /
                  exempt) with its base and head token counts.

Token measure: bytes / 4.  Limit: 5000 tokens (issue #23).
Size source: local git clones (the sandbox has no GitHub API access, so
``gh`` numstat is unavailable -- see the report's "unmeasurable" notes).

Usage:
    python3 bin/filesize_phase0.py inventory [--clone-root ~/workspace]
    python3 bin/filesize_phase0.py retrospective [--ledger PATH] [--rows 60]
    python3 bin/filesize_phase0.py all [--clone-root ~/workspace]

Options:
    --clone-root DIR   Root holding the supervisor-loop clones
                       (default: ~/workspace).
    --ledger PATH      Worker ledger jsonl (default: the manager-setup
                       ledger path, overridable).
    --rows N           Number of most recent pr_opened rows to analyse
                       (default: 60).
    --limit-tokens N   Token limit for "over" (default: 5000).
    --format FORMAT    markdown | tsv | csv (default: markdown).
    --repo-dir NAME=PATH
                       Override the clone directory for one repo.
"""
