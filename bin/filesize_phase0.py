def tracked_files(repo_dir):
    """Tracked files with their blob size at HEAD: [(path, size_bytes)]."""
    rc, out, _ = git(repo_dir, "ls-tree", "-r", "-l", "-z", "HEAD")
    if rc != 0:
        rc, out, _ = git(repo_dir, "ls-files", "-z")
        if rc != 0:
            return []
        entries = []
        for path in out.split("\0"):
            if not path:
                continue
            full = os.path.join(repo_dir, path)
            try:
                entries.append((path, os.path.getsize(full)))
            except OSError:
                continue
        return entries
    entries = []
    for record in out.split("\0"):
        if not record:
            continue
        meta, _, path = record.partition("\t")
        parts = meta.split()
        if len(parts) < 4:
            continue
        try:
            size = int(parts[3])
        except ValueError:
            size = 0
        entries.append((path, size))
    return entries


