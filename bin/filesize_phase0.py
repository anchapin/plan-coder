def render_table(rows, columns, fmt):
    """Render rows as a markdown / tsv / csv table."""
    if fmt == "tsv":
        lines = ["\t".join(columns)]
        lines.extend("\t".join(str(row.get(c, "")) for c in columns) for row in rows)
        return "\n".join(lines)
    if fmt == "csv":
        buffer = io.StringIO()
        writer = csv.DictWriter(buffer, fieldnames=columns, extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow(row)
        return buffer.getvalue().rstrip("\n")
    lines = ["| " + " | ".join(columns) + " |", "|" + "|".join(["---"] * len(columns)) + "|"]
    for row in rows:
        lines.append("| " + " | ".join(str(row.get(c, "")) for c in columns) + " |")
    return "\n".join(lines)


def parse_overrides(pairs):
    overrides = {}
    for pair in pairs or []:
        if "=" not in pair:
            raise SystemExit(f"--repo-dir expects NAME=PATH, got {pair!r}")
        name, path = pair.split("=", 1)
        overrides[name.strip()] = os.path.abspath(os.path.expanduser(path.strip()))
    return overrides


