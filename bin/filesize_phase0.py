def read_ledger(path):
    """Read the worker ledger jsonl; return the list of parsed rows."""
    rows = []
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            line = line.strip()
            if not line:
                continue
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows


def blob_size(repo_dir, rev, path):
    """Byte size of path at rev, or 0 when the path is absent there."""
    rc, out, _ = git(repo_dir, "cat-file", "-s", f"{rev}:{path}")
    if rc != 0:
        return 0
    try:
        return int(out.strip())
    except ValueError:
        return 0


def blob_head(repo_dir, rev, path):
    """First 2000 bytes of path at rev (empty string when absent)."""
    rc, out, _ = git(repo_dir, "show", f"{rev}:{path}")
    if rc != 0:
        return ""
    return out[:2000]


def changed_files(repo_dir, base, head):
    """Return [(status, old_path, new_path)] between base and head."""
    rc, out, _ = git(repo_dir, "diff", "--name-status", "-z", "--find-renames", base, head)
    if rc != 0:
        return []
    fields = [f for f in out.split("\0") if f != ""]
    entries = []
    index = 0
    while index < len(fields):
        status = fields[index]
        code = status[0]
        if code in ("R", "C"):
            old_path = fields[index + 1]
            new_path = fields[index + 2]
            entries.append((code, old_path, new_path))
            index += 3
        else:
            path = fields[index + 1]
            entries.append((code, path, path))
            index += 2
    return entries


def resolve_head(repo_dir, branch):
    """Resolve a branch name to a commit sha; returns (sha, reason)."""
    if not branch:
        return None, "no branch recorded in ledger"
    for ref in (branch, f"origin/{branch}", f"refs/heads/{branch}"):
        rc, out, _ = git(repo_dir, "rev-parse", "--verify", "--quiet", ref)
        if rc == 0 and out.strip():
            return out.strip(), None
    return None, f"branch {branch} not present in local clone"


def resolve_base(repo_dir, branch, head_sha, base_ref):
    """Resolve the PR base commit for a worker branch; returns (sha, source).

    Preference order:
      1. the reflog "branch: Created from <ref>" entry -- this is exactly the
         commit the worker branched off, i.e. the PR base;
      2. the merge-base with the default branch, when the branch is not yet
         merged (it is the PR base);
      3. the first parent of the merge commit that brought the branch in,
         when the branch was merged before the clone was inspected.
    """
    rc, out, _ = git(repo_dir, "reflog", "show", "--format=%H %gs", branch)
    if rc == 0:
        for line in out.splitlines():
            if "branch: Created from" in line:
                sha = line.split(" ", 1)[0].strip()
                if sha:
                    return sha, "reflog branch-creation point"
    rc, out, _ = git(repo_dir, "merge-base", base_ref, head_sha)
    if rc == 0 and out.strip() and out.strip() != head_sha:
        return out.strip(), f"merge-base with {base_ref}"
    rc, out, _ = git(repo_dir, "rev-list", "--ancestry-path", "--merges", f"{head_sha}..{base_ref}")
    if rc == 0:
        merges = [line for line in out.splitlines() if line.strip()]
        if merges:
            merge_sha = merges[-1]
            rc, first_parent, _ = git(repo_dir, "rev-parse", "--verify", "--quiet", f"{merge_sha}^1")
            if rc == 0 and first_parent.strip():
                return first_parent.strip(), "first parent of the merge commit"
    return None, "no base commit resolvable in local clone"


def classify_file(base_tokens, head_tokens, limit_tokens, reason):
    """Classify one changed file per the issue #23 definitions.

    Returns a dict with the class name plus the growth threshold used and a
    "flat" flag: a file that is over the limit at both ends but grew by no
    more than max(100 tokens, 2%) is over the limit without materially
    growing.  The class vocabulary has no separate name for that state, so
    it is reported as over-growing with the flat flag set, and the report
    quotes both a literal and a threshold-strict would-block rate.
    """
    growth = head_tokens - base_tokens
    threshold = max(100, int(base_tokens * 0.02))
    result = {"class": "under", "flat": False, "growth": growth, "threshold": threshold}
    if reason:
        result["class"] = "exempt"
        return result
    if head_tokens > limit_tokens:
        if base_tokens == 0:
            result["class"] = "new-over"
            return result
        if base_tokens <= limit_tokens:
            result["class"] = "crossing"
            return result
        if growth < 0:
            result["class"] = "over-shrinking"
            return result
        result["class"] = "over-growing"
        result["flat"] = growth <= threshold
        return result
    result["class"] = "under"
    return result


def run_retrospective(args, overrides):
    """Classify every file changed by the most recent pr_opened rows."""
    rows = read_ledger(args.ledger)
    pr_rows = [r for r in rows if r.get("outcome") == "pr_opened"]
    selected = pr_rows[-args.rows :] if args.rows > 0 else pr_rows
    table = []
    pr_status = []
    for row in selected:
        repo = str(row.get("repo") or "")
        branch = str(row.get("branch") or "")
        pr_url = str(row.get("pr_url") or "")
        pr_number = pr_url.rstrip("/").split("/")[-1] if pr_url else ""
        run_id = str(row.get("run_id") or "")
        repo_dir = resolve_clone(repo, args.clone_root, overrides)
        if repo_dir is None:
            pr_status.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "status": "unmeasurable",
                    "reason": "clone not found under clone root",
                    "blocking": False,
                }
            )
            continue
        head_sha, reason = resolve_head(repo_dir, branch)
        if head_sha is None:
            pr_status.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "status": "unmeasurable",
                    "reason": reason,
                    "blocking": False,
                }
            )
            continue
        base_ref = default_base_ref(repo_dir)
        if base_ref is None:
            pr_status.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "status": "unmeasurable",
                    "reason": "no default branch in clone",
                    "blocking": False,
                }
            )
            continue
        base_sha, base_source = resolve_base(repo_dir, branch, head_sha, base_ref)
        if base_sha is None:
            pr_status.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "status": "unmeasurable",
                    "reason": base_source,
                    "blocking": False,
                }
            )
            continue
        entries = changed_files(repo_dir, base_sha, head_sha)
        if not entries:
            pr_status.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "status": "no-diff",
                    "reason": "branch tip identical to base",
                    "blocking": False,
                }
            )
            continue
        blocking = False
        blocking_strict = False
        for status, old_path, new_path in entries:
            base_bytes = blob_size(repo_dir, base_sha, old_path)
            head_bytes = blob_size(repo_dir, head_sha, new_path)
            base_tokens = tokens_of(base_bytes)
            head_tokens = tokens_of(head_bytes)
            content = blob_head(repo_dir, head_sha, new_path) if head_bytes else ""
            exempt = exemption_reason(new_path, content)
            verdict = classify_file(base_tokens, head_tokens, args.limit_tokens, exempt)
            klass = verdict["class"]
            if klass in ("new-over", "crossing", "over-growing"):
                blocking = True
                if not (klass == "over-growing" and verdict["flat"]):
                    blocking_strict = True
            detail = exempt or ""
            if status == "D":
                detail = (detail + "; " if detail else "") + "deleted"
            if klass == "over-growing" and verdict["flat"]:
                detail = "flat"
            table.append(
                {
                    "run_id": run_id,
                    "repo": repo,
                    "pr": pr_number,
                    "file": new_path,
                    "class": klass,
                    "base_tokens": base_tokens,
                    "head_tokens": head_tokens,
                    "growth": verdict["growth"],
                    "reason": detail,
                }
            )
        pr_status.append(
            {
                "run_id": run_id,
                "repo": repo,
                "pr": pr_number,
                "status": "measured",
                "reason": f"base from {base_source}",
                "blocking": blocking,
                "blocking_strict": blocking_strict,
            }
        )
    return table, pr_status


