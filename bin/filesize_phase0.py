def is_binary(repo_dir, path):
    """True for binary assets (known extension, or a NUL byte in the file)."""
    if path.lower().endswith(BINARY_EXTENSIONS):
        return True
    try:
        with open(os.path.join(repo_dir, path), "rb") as handle:
            return b"\0" in handle.read(8192)
    except OSError:
        return False


def inventory(repo_dir, limit_tokens):
    """Inventory of one clone: per category file counts and token totals."""
    buckets = defaultdict(lambda: {"files": 0, "tokens": 0, "over": 0, "max": 0})
    excluded = {"data": 0, "binary": 0}
    for path, size in tracked_files(repo_dir):
        lowered = path.lower()
        if any(part in lowered for part in EXCLUDED_PATH_PARTS):
            continue
        if any(part in lowered for part in DATA_PATH_PARTS):
            excluded["data"] += 1
            continue
        if is_binary(repo_dir, path):
            excluded["binary"] += 1
            continue
        toks = tokens_of(size)
        bucket = buckets[classify_category(path)]
        bucket["files"] += 1
        bucket["tokens"] += toks
        bucket["max"] = max(bucket["max"], toks)
        if toks > limit_tokens:
            bucket["over"] += 1
    return buckets, excluded


def run_inventory(args, overrides):
    """Build the inventory baseline table for every configured repo."""
    rows = []
    excluded_rows = []
    for repo in REPOS:
        repo_dir = resolve_clone(repo, args.clone_root, overrides)
        if repo_dir is None:
            rows.append(
                {
                    "repo": repo,
                    "clone": "",
                    "head": "",
                    "category": "n/a",
                    "files": 0,
                    "tokens": 0,
                    "max_tokens": 0,
                    "over_limit": 0,
                    "status": "clone-missing",
                }
            )
            continue
        buckets, excluded = inventory(repo_dir, args.limit_tokens)
        rc, head_out, _ = git(repo_dir, "rev-parse", "--short", "HEAD")
        head_sha = head_out.strip() if rc == 0 else ""
        for category in ("src", "test", "fixture"):
            bucket = buckets.get(category, {"files": 0, "tokens": 0, "over": 0, "max": 0})
            rows.append(
                {
                    "repo": repo,
                    "clone": os.path.relpath(repo_dir, args.clone_root),
                    "head": head_sha,
                    "category": category,
                    "files": bucket["files"],
                    "tokens": bucket["tokens"],
                    "max_tokens": bucket["max"],
                    "over_limit": bucket["over"],
                    "status": "ok",
                }
            )
        excluded_rows.append(
            {
                "repo": repo,
                "data_files": excluded["data"],
                "binary_files": excluded["binary"],
            }
        )
    return rows, excluded_rows


