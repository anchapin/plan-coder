def headline(table, pr_status):
    """Would-block rate per repo and median head tokens of touched files."""
    per_repo = defaultdict(lambda: {"prs": 0, "blocked": 0, "blocked_strict": 0})
    for pr in pr_status:
        if pr["status"] != "measured":
            continue
        bucket = per_repo[pr["repo"]]
        bucket["prs"] += 1
        if pr["blocking"]:
            bucket["blocked"] += 1
        if pr.get("blocking_strict"):
            bucket["blocked_strict"] += 1
    rates = []
    for repo, bucket in sorted(per_repo.items()):
        prs = bucket["prs"]
        touched_repo = [
            row["head_tokens"] for row in table if row["repo"] == repo and row["head_tokens"] > 0
        ]
        rates.append(
            {
                "repo": repo,
                "prs": prs,
                "blocked": bucket["blocked"],
                "rate": round(100.0 * bucket["blocked"] / prs, 1) if prs else 0.0,
                "blocked_strict": bucket["blocked_strict"],
                "rate_strict": round(100.0 * bucket["blocked_strict"] / prs, 1) if prs else 0.0,
                "median_head_tokens": statistics.median(touched_repo) if touched_repo else 0,
            }
        )
    touched = [row["head_tokens"] for row in table if row["head_tokens"] > 0]
    median = statistics.median(touched) if touched else 0
    return rates, median, len(touched)


