def git(repo_dir, *args):
    """Run a git command in repo_dir; return (rc, stdout, stderr)."""
    proc = subprocess.run(
        ["git", "-C", repo_dir, *args],
        capture_output=True,
        text=True,
        check=False,
    )
    return proc.returncode, proc.stdout, proc.stderr


def tokens_of(byte_count):
    """Token estimate for a file of byte_count bytes (bytes / 4)."""
    if byte_count <= 0:
        return 0
    return int(round(byte_count / TOKEN_BYTES))


def path_segments(path):
    """Lower-cased directory segments of a repo-relative path (no filename)."""
    parts = path.lower().split("/")
    return parts[:-1], parts[-1]


def is_fixture_path(path):
    """True when the path lives in a fixture / snapshot / testdata tree."""
    dirs, name = path_segments(path)
    for segment in dirs:
        for pattern in FIXTURE_PATTERNS:
            if pattern in segment:
                return True
    if name.endswith(".snap"):
        return True
    return False


def is_test_path(path):
    """True when the path lives in a test tree or is a test-named file."""
    dirs, name = path_segments(path)
    for segment in dirs:
        if segment in TEST_DIR_NAMES:
            return True
        if segment.startswith(("test-", "test_")):
            return True
    for pattern in TEST_FILE_PATTERNS:
        if pattern in name:
            return True
    return False


def classify_category(path):
    """Split a repo-relative path into src / test / fixture."""
    if is_fixture_path(path):
        return "fixture"
    if is_test_path(path):
        return "test"
    return "src"


def exemption_reason(path, head_content):
    """Return an exemption reason for path, or None when not exempt."""
    name = os.path.basename(path).lower()
    if name in LOCKFILE_NAMES:
        return "lockfile"
    lowered = path.lower()
    for part in ("vendor/", "third_party/", "thirdparty/", "node_modules/"):
        if part in lowered:
            return "vendored"
    if is_fixture_path(path):
        return "fixture"
    if head_content:
        head = head_content[:2000].lower()
        for marker in GENERATED_MARKERS:
            if marker in head:
                return "generated-header"
    return None


def resolve_clone(repo, clone_root, overrides):
    """Return the clone directory for repo, or None when unavailable."""
    if repo in overrides:
        return overrides[repo]
    candidates = [repo] + REPO_DIR_CANDIDATES.get(repo, [])
    for candidate in candidates:
        path = os.path.join(clone_root, candidate)
        if os.path.isdir(os.path.join(path, ".git")) or os.path.isfile(
            os.path.join(path, ".git")
        ):
            return path
    return None


def default_base_ref(repo_dir):
    """Default branch of the clone (origin/HEAD, else origin/main/develop)."""
    rc, out, _ = git(repo_dir, "symbolic-ref", "--short", "refs/remotes/origin/HEAD")
    if rc == 0 and out.strip():
        return out.strip()
    for candidate in ("origin/main", "origin/develop", "origin/master"):
        rc, _, _ = git(repo_dir, "rev-parse", "--verify", "--quiet", candidate)
        if rc == 0:
            return candidate
    return None


